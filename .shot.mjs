import { chromium } from "playwright-core";
const out = process.argv[2];
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1000, height: 600 } });
await p.goto("http://localhost:4373/"); await p.waitForTimeout(800);
await p.locator("#ta").fill("Hello from Green Page.\nSecond line.");
await p.waitForTimeout(600);
await p.screenshot({ path: out + "/light.png" });
await p.locator("#btnOpen").click(); await p.waitForTimeout(200);
await p.screenshot({ path: out + "/menu.png" });
await p.locator("#openMenuDraft").click(); await p.waitForTimeout(300);
await p.screenshot({ path: out + "/drafts.png" });
await p.keyboard.press("Escape");
await p.locator("#btnSave").click(); await p.waitForTimeout(300);
await p.screenshot({ path: out + "/save.png" });
await p.keyboard.press("Escape");
await p.locator("#btnSettings").click(); await p.waitForTimeout(300);
await p.locator('input[name="theme"][value="dark"]').check(); await p.locator('input[name="font"][value="mono"]').check();
await p.screenshot({ path: out + "/settings.png" });
await p.locator("#settingsApply").click(); await p.waitForTimeout(800);
await p.screenshot({ path: out + "/dark-mono.png" });
await b.close();
